"""Generate the x64 winmm proxy's checked-in thunks, exports and lookup metadata.

Only the Python standard library is used. --check accepts a committed superset
of the current system exports, so an older Windows installation still builds.
"""

import argparse
import json
import os
from pathlib import Path
import struct
import sys


def read_exports(path):
    data = Path(path).read_bytes()

    def unpack(fmt, offset):
        return struct.unpack_from('<' + fmt, data, offset)

    if data[:2] != b'MZ':
        raise ValueError('not a DOS/PE image')
    pe, = unpack('I', 0x3c)
    if data[pe:pe + 4] != b'PE\0\0':
        raise ValueError('bad PE signature')
    machine, sections = unpack('HH', pe + 4)
    optional_size, = unpack('H', pe + 20)
    optional = pe + 24
    magic, = unpack('H', optional)
    if machine != 0x8664 or magic != 0x20b:
        raise ValueError('expected an AMD64 PE32+ image')
    size_headers, = unpack('I', optional + 60)
    section_table = optional + optional_size

    def offset(rva):
        if rva < size_headers:
            return rva
        for i in range(sections):
            virtual_size, virtual, raw_size, raw = unpack('IIII', section_table + 40 * i + 8)
            if virtual <= rva < virtual + max(virtual_size, raw_size):
                if rva - virtual >= raw_size:
                    raise ValueError('RVA points at uninitialised section data')
                return raw + rva - virtual
        raise ValueError(f'unmapped RVA {rva:#x}')

    export_rva, = unpack('I', optional + 112)
    if not export_rva:
        return []
    base, count, name_count, functions, names, ordinals = unpack('IIIIII', offset(export_rva) + 16)
    by_index = {}
    for i in range(name_count):
        name_rva, = unpack('I', offset(names) + 4 * i)
        index, = unpack('H', offset(ordinals) + 2 * i)
        if index >= count:
            raise ValueError('export name has an invalid ordinal index')
        start = offset(name_rva)
        name = data[start:data.index(b'\0', start)].decode('ascii')
        if not name or any(c not in 'abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789_@?$' for c in name):
            raise ValueError(f'unsupported export name {name!r}')
        by_index.setdefault(index, []).append(name)
    result = []
    for i in range(count):
        address, = unpack('I', offset(functions) + 4 * i)
        if address:
            if not 1 <= base + i <= 65535:
                raise ValueError('export ordinal is outside GetProcAddress range')
            result.append({'ordinal': base + i, 'names': sorted(by_index.get(i, []))})
    return result


def generate(exports):
    banner = '// Generated by generate_exports.py; do not edit.\n'
    header = banner + '#pragma once\n#include <cstddef>\n#include <cstdint>\n\nnamespace nl::proxy {\n'
    header += 'struct ExportSpec { const char* name; std::uint16_t ordinal; };\n'
    header += 'inline constexpr ExportSpec kExports[] = {\n'
    definition = '; Generated by generate_exports.py; do not edit.\nLIBRARY winmm\nEXPORTS\n'
    assembly = '; Generated by generate_exports.py; do not edit.\noption casemap:none\nEXTERN nl_forward_table:QWORD\n.code\n'
    for i, entry in enumerate(exports):
        ordinal, names = entry['ordinal'], entry['names']
        header += f'  {{{json.dumps(names[0]) if names else "nullptr"}, {ordinal}}},\n'
        for name in names:
            definition += f'  {name}=nl_forward_{i} @{ordinal}\n'
        if not names:
            definition += f'  nl_ordinal_{ordinal}=nl_forward_{i} @{ordinal} NONAME\n'
        assembly += f'PUBLIC nl_forward_{i}\nnl_forward_{i} PROC\n  jmp QWORD PTR [nl_forward_table + {8 * i}]\nnl_forward_{i} ENDP\n'
    header += '};\ninline constexpr std::size_t kExportCount = sizeof(kExports) / sizeof(kExports[0]);\n}  // namespace nl::proxy\n'
    assembly += 'END\n'
    return {'exports.h': header, 'winmm.def': definition, 'thunks.asm': assembly,
            'exports.json': json.dumps(exports, indent=2) + '\n'}


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument('--dll', type=Path, default=Path(os.environ.get('SystemRoot', r'C:\Windows')) / 'System32/winmm.dll')
    parser.add_argument('--output', type=Path, default=Path(__file__).resolve().parent / 'generated')
    parser.add_argument('--check', action='store_true', help='verify current system exports and generated-file consistency')
    args = parser.parse_args()
    try:
        system = read_exports(args.dll)
        if args.check:
            committed = json.loads((args.output / 'exports.json').read_text(encoding='utf-8'))
            available = {e['ordinal']: set(e['names']) for e in committed}
            for entry in system:
                if entry['ordinal'] not in available or not set(entry['names']) <= available[entry['ordinal']]:
                    raise ValueError(f'proxy lacks system export {entry}; run generate_exports.py')
            for name, content in generate(committed).items():
                if (args.output / name).read_text(encoding='utf-8') != content:
                    raise ValueError(f'{name} is stale; run generate_exports.py')
            print(f'winmm exports OK: {len(system)} system ordinals covered, generated files consistent')
        else:
            args.output.mkdir(parents=True, exist_ok=True)
            for name, content in generate(system).items():
                (args.output / name).write_text(content, encoding='utf-8', newline='\n')
            print(f'Generated {len(system)} ordinals, {sum(len(e["names"]) for e in system)} names, '
                  f'{sum(not e["names"] for e in system)} ordinal-only exports from {args.dll}')
        return 0
    except (OSError, ValueError, struct.error) as error:
        print(f'export generation failed: {error}', file=sys.stderr)
        return 1


if __name__ == '__main__':
    sys.exit(main())
