#include "nl/gpu_diagnostics.h"
#include "nl/fs.h"
#include <windows.h>

namespace nl::gpu_diagnostics {
namespace {
void directory(const std::filesystem::path& root, std::string_view relative) {
  fs::refuse_links(root, relative);
  const auto path = fs::join(root, relative);
  const auto info = fs::stat(path);
  if (!info.exists) {
    try { fs::win32().create_directory(path); }
    catch (const fs::Error& error) {
      const auto raced = fs::stat(path);
      if (error.code() != ERROR_ALREADY_EXISTS || !raced.directory || raced.link) throw;
    }
  } else if (info.directory && !info.link) return;
  else throw fs::Error("GPU diagnostics parent is not an ordinary directory: " + fs::utf8(path), 0);
}
std::string dump_path(const std::filesystem::path& root) {
  return fs::utf8(std::filesystem::absolute(fs::join(root, kDumpFolder)).lexically_normal()) + '/';
}
}  // namespace

Probe probe(const std::filesystem::path& root) {
  Probe result;
  try {
    result.dump_path = dump_path(root);
    fs::refuse_links(root, kUsed);
    result.consumed = fs::stat(fs::join(root, kUsed)).exists;
  } catch (const std::exception& error) {
    result.consumed = true;
    result.note = std::string("GPU diagnostics next_start state could not be read; treating it as consumed: ") + error.what();
  }
  return result;
}

std::string layer_text() {
  return "# Generated by the GMod native loader for opt-in GPU crash diagnostics (ADR 0062).\r\n"
         "# All three keys use DXVK's merged startup Config, including rtx.enableGpuCrashState.\r\n"
         "dxvk.enableAftermath = True\r\n"
         "dxvk.enableAftermathResourceTracking = True\r\n"
         "rtx.enableGpuCrashState = True\r\n";
}

std::string prepare(const std::filesystem::path& root) {
  for (const char* relative : {"native-loader", "native-loader/remix", "native-loader/logs", "native-loader/logs/gpu"})
    directory(root, relative);
  fs::refuse_links(root, kLayer);
  const auto file = fs::join(root, kLayer);
  const auto text = layer_text();
  const auto info = fs::stat(file);
  if (!info.exists || info.directory || info.size != text.size() || fs::read_file(file, text.size() + 1) != text)
    fs::write_atomic(fs::win32(), file, text);
  return dump_path(root);
}

bool consume_next_start(const std::filesystem::path& root) {
  directory(root, "native-loader");
  directory(root, "native-loader/remix");
  fs::refuse_links(root, kUsed);
  try {
    auto marker = fs::win32().create_file(fs::join(root, kUsed));  // CREATE_NEW, so only one start wins
    constexpr std::string_view text = "GPU diagnostics next_start consumed; remove this loader-owned marker to request again.\r\n";
    marker->write(text.data(), text.size());
    marker->close();
    return true;
  } catch (const fs::Error& error) {
    if (error.code() == ERROR_FILE_EXISTS || error.code() == ERROR_ALREADY_EXISTS) return false;
    throw;
  }
}

void reset_next_start(const std::filesystem::path& root) {
  fs::refuse_links(root, kUsed);
  const auto path = fs::join(root, kUsed);
  if (fs::stat(path).exists) fs::win32().remove_file(path);
}
}  // namespace nl::gpu_diagnostics
