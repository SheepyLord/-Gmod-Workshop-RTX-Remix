#pragma once
// Console variables for RTX sessions only (M5, ADR 0010). The game archives most variables into its
// own garrysmod/cfg/config.cfg when it quits, so a value an RTX session sets would carry into the
// next RTX-off session. The loader therefore records the user's archived values before the first RTX
// session that changes them, runs the RTX values through a generated cfg (+exec), and at the next
// start without RTX runs a generated cfg that puts the recorded values back, once.

#include "nl/journal.h"

#include <filesystem>
#include <map>
#include <optional>
#include <stdexcept>
#include <string>
#include <string_view>
#include <utility>
#include <vector>

namespace nl::session {

class Error : public std::runtime_error {
 public:
  using std::runtime_error::runtime_error;
};

using Values = std::vector<std::pair<std::string, std::string>>;

inline constexpr std::string_view kRecordPath = "native-loader/session_cvars.json";
inline constexpr std::string_view kSessionCfg = "garrysmod/cfg/nativeloader_session.cfg";
inline constexpr std::string_view kRestoreCfg = "garrysmod/cfg/nativeloader_restore.cfg";
inline constexpr std::string_view kConfigCfg = "garrysmod/cfg/config.cfg";
inline constexpr std::string_view kHeader = "// Generated by the GMod native loader";

// The values config.cfg archives, by lower-cased name: lines of the form `name "value"`.
std::map<std::string, std::string> parse_config(std::string_view text);

// The restore record (native-loader/session_cvars.json).
struct Record {
  Values values;               // the user's archived values before RTX sessions changed them
  bool restore_issued = false;  // a start without RTX has already run the restore cfg
};
std::string serialize(const Record& record);
Record parse_record(std::string_view json_text);  // throws Error

// What one start does about session variables. Pure: the bootstrap carries it out.
struct Plan {
  bool drop_record = false;   // the record's restore has run: forget it before anything else
  Values record;              // the record to keep afterwards (empty: none)
  bool write_session = false;  // RTX session: write kSessionCfg with `session` and +exec it
  Values session;
  bool write_restore = false;  // start without RTX: write kRestoreCfg with `restore` and +exec it
  Values restore;
  std::vector<std::string> exec_args;  // "+exec", "<file>" to add to the command line
};
Plan plan(bool rtx_session, const Values& cvars, const std::optional<Record>& record,
          const std::map<std::string, std::string>& config);

// The text of a generated cfg file.
std::string cfg_text(const Values& values, std::string_view purpose);

// True if `path` does not exist or is a file this loader generated (it starts with kHeader).
bool ours_or_absent(const std::filesystem::path& path);

// The add-on folders (names under garrysmod/addons, lower-case, sorted) that packages marked
// requires_remix placed in `generation`: hidden from a session without an active runtime (ADR 0013).
std::vector<std::string> hidden_addons(const journal::Generation& generation);

}  // namespace nl::session
