"""Writes the companion's table of classic RTX settings: the values the reference install (the user's
classic RTX install, GarrysMod_RTX_c) saved for the RTX add-ons' console variables, which the
companion applies once as first-run defaults (ADR 0020). Reads only; writes the one Lua file."""
import argparse
import datetime as _dt
import re
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
REFERENCE = Path(r'H:\SteamLibrary\steamapps\common\GarrysMod_RTX_c')
OUT = REPO / 'companion' / 'nativeloader' / 'lua' / 'nativeloader' / 'classic_defaults.lua'
# The RTX fixes (rtx_*), the Model Hotloader's RTX options (mhrtx_*), gm_br_rtx (brrtx_*), the fixes'
# hardware-skinning variables and the Advanced MMD Animation Player's flashlight (mmd_vmd_npc_flashlight_*,
# which drives a Remix light in RTX sessions). Debug switches are left out: they are developer tools.
INCLUDE = r'^(rtx_|mhrtx_|brrtx_|r_hwskin|r_eyes_hwskin|r_forcehw|mmd_vmd_npc_flashlight_)'
EXCLUDE = r'(^|_)debug(_|$)|_debug_|^rtx_capture_mode$|^rtx_mwr_capture_mode$|_key$'
VERSION = 3  # raise it when the table changes so players get the new values once more


def read_vdf(path: Path) -> dict:
    """The "name" "value" pairs of a GMod cvar .vdf (cfg/client.vdf, cfg/server.vdf)."""
    text = path.read_text(encoding='utf-8', errors='replace')
    return {m.group(1).lower(): m.group(2) for m in re.finditer(r'"([^"\n]+)"\s+"([^"\n]*)"', text)}


def lua_string(text: str) -> str:
    return '"' + text.replace('\\', '\\\\').replace('"', '\\"') + '"'


def generate(reference: Path, include: str = INCLUDE, exclude: str = EXCLUDE, version: int = VERSION) -> tuple[str, dict]:
    keep, drop = re.compile(include), re.compile(exclude)
    realms = {}
    for realm in ('client', 'server'):
        source = reference / 'garrysmod' / 'cfg' / f'{realm}.vdf'
        if not source.is_file():
            raise FileNotFoundError(f'{source} is missing')
        values = read_vdf(source)
        realms[realm] = {k: v for k, v in sorted(values.items()) if keep.search(k) and not drop.search(k)}
    # In single-player the client and the server share one variable of each name, and the client's saved
    # value is applied last, so a name saved in both files has the client's value. The classic install's
    # server.vdf keeps stale copies (rtx_pseudoplayer "1" against the client's "0"); applying them from
    # the server table brought the pseudo player back. The server table leaves those names out.
    shadowed = [name for name in realms['server'] if name in realms['client']]
    realms['server'] = {k: v for k, v in realms['server'].items() if k not in realms['client']}
    lines = ['-- Generated by tools/classic_defaults.py; do not edit. The RTX settings of the classic install',
             f'-- ({reference.name}, cfg/client.vdf and cfg/server.vdf, {_dt.date.today().isoformat()}), applied once',
             '-- as first-run defaults by nativeloader_defaults.lua (ADR 0020). A name saved in both files is',
             '-- in the client table only: in single-player both realms share it and the client value wins.',
             'return {', f'  version = {version},']
    for realm, values in realms.items():
        lines.append(f'  {realm} = {{')
        lines += [f'    {name} = {lua_string(value)},' for name, value in values.items()]
        lines.append('  },')
    lines.append('}')
    counts = {realm: len(values) for realm, values in realms.items()}
    counts['shadowed'] = len(shadowed)
    return '\n'.join(lines) + '\n', counts


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--reference', type=Path, default=REFERENCE, help='the classic RTX install (read only)')
    parser.add_argument('--out', type=Path, default=OUT, help='the Lua table to write')
    parser.add_argument('--version', type=int, default=VERSION, help='table version (players get a new version once)')
    parser.add_argument('--check', action='store_true', help='exit 1 when --out differs from what would be written')
    args = parser.parse_args(argv)
    try:
        text, counts = generate(args.reference, version=args.version)
    except FileNotFoundError as error:
        print(f'error: {error}', file=sys.stderr)
        return 1
    current = args.out.read_text(encoding='utf-8') if args.out.is_file() else None
    # The date line differs every day; compare the rest.
    same = current is not None and current.splitlines()[2:] == text.splitlines()[2:]
    if args.check:
        print('up to date' if same else f'{args.out} differs from the reference')
        return 0 if same else 1
    if not same:
        args.out.parent.mkdir(parents=True, exist_ok=True)
        args.out.write_text(text, encoding='utf-8', newline='\n')
    print(f'{args.out}: client {counts["client"]}, server {counts["server"]} settings ({counts["shadowed"]} '
          'server values left out, saved for the client too)' + ('' if not same else ' (unchanged)'))
    return 0


if __name__ == '__main__':
    sys.exit(main())
