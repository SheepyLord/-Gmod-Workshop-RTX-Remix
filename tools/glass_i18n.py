"""Build/check G1's MIT gettext catalogs using the companion's parser, extractor and Lua escaping."""
import argparse
from pathlib import Path
import sys

import companion_i18n as i18n

REPO = Path(__file__).resolve().parents[1]
ROOT = REPO / 'glass/addon/lua'
CATALOGS = REPO / 'glass/i18n'
OUTPUT = ROOT / 'nlglass/i18n_data.lua'


def update():
    strings = i18n.extract(str(ROOT))
    i18n.write_po(str(CATALOGS / 'glass.pot'), None, strings, {})
    for language in i18n.LANGUAGES:
        path = CATALOGS / (language + '.po')
        old = {e['msgid']: (e['msgstr'], e['fuzzy']) for e in i18n.read_po(str(path)) if e['msgid']} if path.exists() else {}
        i18n.write_po(str(path), language, strings, old)
    # The shared writer has companion-specific comments; this catalog and its provenance are MIT.
    for path in CATALOGS.glob('*.po*'):
        text = path.read_text(encoding='utf-8').replace('GMod native loader companion', 'GMod native loader glass')
        text = text.replace('companion/i18n/README.md', 'glass/i18n/README.md').replace('companion/nativeloader/lua', 'glass/addon/lua')
        path.write_text('# MIT; translations written for G1.\n' + text, encoding='utf-8', newline='\n')


def check():
    return i18n.check(str(CATALOGS), str(ROOT), complete=True, unchanged={})


def build(out=OUTPUT):
    text = i18n.build_text(check())
    body = text.split('return ', 1)[1]
    text = '-- MIT. Generated by tools/glass_i18n.py build from glass/i18n/*.po; do not edit.\nreturn ' + body
    Path(out).write_text(text, encoding='utf-8', newline='\n')


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('command', choices=('update', 'check', 'build'))
    parser.add_argument('--out', type=Path, default=OUTPUT)
    args = parser.parse_args(argv)
    try:
        if args.command == 'update':
            update()
        elif args.command == 'build':
            build(args.out)
        else:
            check()
    except (i18n.I18nError, OSError) as error:
        print(error, file=sys.stderr)
        return 1
    print('glass translations ' + args.command + ' OK')
    return 0


if __name__ == '__main__':
    sys.exit(main())
