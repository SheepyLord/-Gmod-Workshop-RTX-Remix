REPO = Path(__file__).resolve().parents[2]
LUA = REPO / 'glass/addon/lua'


def luajit():
    local = Path(os.environ.get('LOCALAPPDATA', '')) / 'Programs/LuaJIT/bin/luajit.exe'
    return shutil.which('luajit') or (str(local) if local.is_file() else None)


