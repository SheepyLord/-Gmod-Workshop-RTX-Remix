class GlassCatalogTests(unittest.TestCase):
    def test_complete_mit_catalogs_and_exact_generated_shipping_data(self):
        tables = glass_i18n.check()
        expected = '-- MIT. Generated by tools/glass_i18n.py build from glass/i18n/*.po; do not edit.\nreturn '
        expected += companion_i18n.build_text(tables).split('return ', 1)[1]
        self.assertEqual(glass_i18n.OUTPUT.read_text(encoding='utf-8'), expected)
        self.assertEqual(set(tables), set(companion_i18n.LANGUAGES))
        for language, table in tables.items():
            self.assertGreaterEqual(len(table), 28, language)
        self.assertIn('MIT', (REPO / 'glass/i18n/README.md').read_text(encoding='utf-8'))

    @unittest.skipUnless(luajit(), 'LuaJIT is not installed')
    def test_all_lua_compiles_without_glua_rewriting(self):
        for path in LUA.rglob('*.lua'):
            result = subprocess.run([luajit(), '-e', 'assert(loadfile(%s))' % companion_i18n.lua_quote(str(path))],
                                    cwd=REPO, capture_output=True, encoding='utf-8', timeout=15)
            self.assertEqual(result.returncode, 0, str(path) + '\n' + result.stderr)


